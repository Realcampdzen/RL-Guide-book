export function getVozhatifikatorLevel(totalPoints: number): VozhatifikatorLevel {
  const sorted = [...VOZHATIFIKATOR_LEVELS].sort((a, b) => b.min - a.min);
  const level = sorted.find((l) => totalPoints >= l.min);
  return level ?? VOZHATIFIKATOR_LEVELS[0];
}
